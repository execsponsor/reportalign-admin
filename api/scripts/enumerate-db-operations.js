/**
 * B4.1 — enumerate every table/operation pair this API performs.
 *
 * Static analysis of the SQL literals in src/, so the grant set is derived from the code rather
 * than from memory. Deliberately conservative: anything it cannot classify is reported as
 * UNPARSED rather than silently dropped, because a missed write becomes a runtime failure after
 * the role cuts over.
 *
 *   node api/scripts/enumerate-db-operations.js            # table
 *   node api/scripts/enumerate-db-operations.js --sql      # emit the GRANT statements
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', 'src');
const EMIT_SQL = process.argv.includes('--sql');

const ops = new Map();   // table -> Set(op)
const unparsed = [];

function note(table, op) {
  const t = table.replace(/^public\./, '').replace(/["`]/g, '').toLowerCase();
  if (!/^[a-z_][a-z0-9_]*$/.test(t)) { return; }
  if (!ops.has(t)) { ops.set(t, new Set()); }
  ops.get(t).add(op);
}

function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) { walk(p); continue; }
    if (!entry.name.endsWith('.ts')) { continue; }
    scan(p, fs.readFileSync(p, 'utf8'));
  }
}

function scan(file, src) {
  // SQL appears in template literals and quoted strings passed to pool.query / client.query.
  const literals = [
    ...src.matchAll(/`([^`]*?)`/gs),
    ...src.matchAll(/'((?:[^'\\]|\\.){20,}?)'/gs),
  ].map((m) => m[1]);

  for (const raw of literals) {
    const sql = raw.replace(/\s+/g, ' ').trim();
    if (!/\b(SELECT|INSERT|UPDATE|DELETE)\b/i.test(sql)) { continue; }

    let matched = false;

    for (const m of sql.matchAll(/\bFROM\s+([a-zA-Z_][\w.]*)/gi)) { note(m[1], 'SELECT'); matched = true; }
    for (const m of sql.matchAll(/\bJOIN\s+([a-zA-Z_][\w.]*)/gi)) { note(m[1], 'SELECT'); matched = true; }
    for (const m of sql.matchAll(/\bINSERT\s+INTO\s+([a-zA-Z_][\w.]*)/gi)) { note(m[1], 'INSERT'); matched = true; }
    for (const m of sql.matchAll(/\bUPDATE\s+([a-zA-Z_][\w.]*)\s+SET/gi)) { note(m[1], 'UPDATE'); matched = true; }
    for (const m of sql.matchAll(/\bDELETE\s+FROM\s+([a-zA-Z_][\w.]*)/gi)) { note(m[1], 'DELETE'); matched = true; }

    // An UPDATE/INSERT with a RETURNING clause also reads.
    if (/\bRETURNING\b/i.test(sql)) {
      for (const m of sql.matchAll(/\b(?:INSERT\s+INTO|UPDATE)\s+([a-zA-Z_][\w.]*)/gi)) { note(m[1], 'SELECT'); }
    }

    if (!matched && /\b(SELECT|INSERT|UPDATE|DELETE)\b/i.test(sql) && sql.length > 40) {
      unparsed.push({ file: path.relative(ROOT, file), sql: sql.slice(0, 90) });
    }
  }
}

walk(ROOT);

/**
 * Cross-check. The literal-based scan above pairs quotes, and a stray apostrophe in a comment
 * ("each handler's order") shifts that pairing and silently swallows the SQL after it — which is
 * how `UPDATE super_administrators SET last_login` went missing on the first run.
 *
 * This second pass ignores literals entirely and sweeps the raw file text for the same verbs. It
 * OVER-approximates (it will pick up SQL inside comments), so it is reported separately as
 * "candidates the literal scan missed" rather than merged in. For a grant set, a missed write is
 * an outage after cutover and a spurious one is only over-permission caught in review — so the
 * failure mode of showing both is the right way round.
 */
const crossCheck = new Map();
(function sweep(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) { sweep(p); continue; }
    if (!entry.name.endsWith('.ts')) { continue; }
    const text = fs.readFileSync(p, 'utf8').replace(/\s+/g, ' ');
    const add = (t, op) => {
      const k = t.replace(/^public\./, '').toLowerCase();
      if (!/^[a-z_][a-z0-9_]*$/.test(k)) { return; }
      if (!crossCheck.has(k)) { crossCheck.set(k, new Set()); }
      crossCheck.get(k).add(op);
    };
    for (const m of text.matchAll(/\bINSERT\s+INTO\s+([a-zA-Z_][\w.]*)/gi)) { add(m[1], 'INSERT'); }
    for (const m of text.matchAll(/\bUPDATE\s+([a-zA-Z_][\w.]*)\s+SET/gi)) { add(m[1], 'UPDATE'); }
    for (const m of text.matchAll(/\bDELETE\s+FROM\s+([a-zA-Z_][\w.]*)/gi)) { add(m[1], 'DELETE'); }
    for (const m of text.matchAll(/\bFROM\s+([a-zA-Z_][\w.]*)/gi)) { add(m[1], 'SELECT'); }
  }
})(ROOT);

const missed = [];
for (const [t, set] of crossCheck) {
  for (const op of set) {
    if (!ops.has(t) || !ops.get(t).has(op)) { missed.push(`${t}:${op}`); }
  }
}

const ORDER = ['SELECT', 'INSERT', 'UPDATE', 'DELETE'];
const tables = [...ops.keys()].sort();

if (EMIT_SQL) {
  console.log('-- Generated by enumerate-db-operations.js. Review before applying.');
  console.log('-- Role name differs by environment; set :role before running.');
  for (const t of tables) {
    const grants = ORDER.filter((o) => ops.get(t).has(o)).join(', ');
    console.log(`GRANT ${grants} ON TABLE public.${t} TO :"role";`);
  }
} else {
  console.log(`Tables touched: ${tables.length}\n`);
  console.log('  table                                 SELECT INSERT UPDATE DELETE');
  console.log('  ' + '-'.repeat(70));
  for (const t of tables) {
    const s = ops.get(t);
    console.log(
      `  ${t.padEnd(38)}` + ORDER.map((o) => (s.has(o) ? '  yes  ' : '   -   ')).join('')
    );
  }
  const writes = tables.filter((t) => ['INSERT', 'UPDATE', 'DELETE'].some((o) => ops.get(t).has(o)));
  console.log(`\n  read-only tables : ${tables.length - writes.length}`);
  console.log(`  written tables   : ${writes.length} -> ${writes.join(', ')}`);

  if (missed.length) {
    console.log(`\n  CROSS-CHECK found ${missed.length} pair(s) the literal scan missed:`);
    missed.sort().forEach((m) => console.log(`     ${m}`));
    console.log('     (over-approximate — may include SQL in comments. Confirm each by hand.)');
  } else {
    console.log('\n  CROSS-CHECK: literal scan and raw sweep agree.');
  }

  console.log(
    '\n  NOTE: this enumeration is a STARTING POINT, not the grant set. Confirm it against the\n' +
    '  runtime verification script before any cutover — a missed write is an outage.'
  );
}
